DROP TABLE IF EXISTS PMMDA_PERFORMANCETESTS_DB.MASTER;
CREATE TABLE PMMDA_PERFORMANCETESTS_DB.MASTER (
  ID INTEGER NOT NULL,
  TS TIMESTAMP NOT NULL,
  PRIMARY KEY(ID)
) TYPE=InnoDB;

CREATE UNIQUE INDEX MASTER_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.MASTER(ID);

DROP TABLE IF EXISTS PMMDA_PERFORMANCETESTS_DB.SLAVE;
CREATE TABLE PMMDA_PERFORMANCETESTS_DB.SLAVE (
  ID INTEGER NOT NULL,
  TS TIMESTAMP NOT NULL,
  VAL INTEGER NOT NULL,
  MASTER_HAS_FK INTEGER,
  PRIMARY KEY(ID)
) TYPE=InnoDB;

CREATE UNIQUE INDEX SLAVE_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.SLAVE(ID);

CREATE INDEX MASTER_HAS_FK_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.SLAVE(MASTER_HAS_FK);

DROP TABLE IF EXISTS PMMDA_PERFORMANCETESTS_DB.NODE;
CREATE TABLE PMMDA_PERFORMANCETESTS_DB.NODE (
  ID INTEGER NOT NULL,
  TS TIMESTAMP NOT NULL,
  VALUE INTEGER NOT NULL,
  RIGHT_FK INTEGER NOT NULL,
  LEFT_FK INTEGER NOT NULL,
  FOREST_TREES_FK INTEGER,
  PRIMARY KEY(ID)
) TYPE=InnoDB;

CREATE UNIQUE INDEX NODE_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.NODE(ID);

CREATE INDEX NODE_RIGHT_FK_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.NODE(RIGHT_FK);

CREATE INDEX NODE_LEFT_FK_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.NODE(LEFT_FK);

CREATE INDEX FOREST_TREES_FK_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.NODE(FOREST_TREES_FK);

DROP TABLE IF EXISTS PMMDA_PERFORMANCETESTS_DB.FOREST;
CREATE TABLE PMMDA_PERFORMANCETESTS_DB.FOREST (
  ID INTEGER NOT NULL,
  TS TIMESTAMP NOT NULL,
  PRIMARY KEY(ID)
) TYPE=InnoDB;

CREATE UNIQUE INDEX FOREST_IDX ON 
  PMMDA_PERFORMANCETESTS_DB.FOREST(ID);

