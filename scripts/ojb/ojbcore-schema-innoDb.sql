drop table if exists OJB.HL_SEQ;
CREATE TABLE OJB.HL_SEQ (
  TABLENAME VARCHAR (175) NOT NULL,
  FIELDNAME VARCHAR (70) NOT NULL,
  MAX_KEY BIGINT,
  GRAB_SIZE INTEGER,
  VERSION INTEGER,
  PRIMARY KEY(TABLENAME,FIELDNAME)
) TYPE=InnoDB;

